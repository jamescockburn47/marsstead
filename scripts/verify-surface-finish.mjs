import assert from 'node:assert/strict';
import * as THREE from 'three';
import {ShipLayer} from '../src/shiplayer.js';
import {RockLayer} from '../src/rocklayer.js';
const scene=new THREE.Scene(),ship=new ShipLayer(scene,null);
const canopy=ship.group.children.find(o=>o.geometry?.type==='LatheGeometry'&&o.geometry.parameters.phiLength<Math.PI*2);
assert(canopy,'ship retains its partial wrap canopy');
const profile=[[1.52,5.9],[1.28,6.7],[.98,7.4],[.62,8.1]];
const radius=y=>{const i=profile.findIndex((p,n)=>n<profile.length-1&&y>=p[1]&&y<=profile[n+1][1]);const [a,b]=[profile[i],profile[i+1]];return a[0]+(b[0]-a[0])*(y-a[1])/(b[1]-a[1]);};
const p=canopy.geometry.attributes.position;
for(let i=0;i<p.count;i++)assert(Math.hypot(p.getX(i),p.getZ(i))>radius(p.getY(i))+.02,'canopy skin stays outside hull: no clipped triangle rim');
const finishBox=new THREE.Box3().setFromObject(ship.finish);
assert(finishBox.min.y>=-.001&&finishBox.max.y<6,'fittings retain original foot plane and main hull silhouette');
assert(ship.finish.children.length<=6,'ship fittings stay batched');
let lights=0;ship.finish.traverse(o=>{if(o.isLight)lights++;if(o.isMesh)assert([...o.geometry.attributes.position.array].every(Number.isFinite));});
assert.equal(lights,0,'no new dynamic ship lights');
ship.setPose(3,10,4,.6,.2);assert.deepEqual(ship.finish.position.toArray(),[0,0,0]);
ship.setFuel(0);assert(ship.tanks.every(t=>!t.visible));
ship.update(0,false);const dayReflection=ship.mats[0].envMapIntensity;
ship.update(0,true);assert(ship.mats[0].envMapIntensity<dayReflection/4,'studio reflections do not illuminate the hull at night');
const rocks=new RockLayer(scene);assert(rocks.mat.isMeshStandardMaterial);
for(const geo of rocks.geos)assert([...geo.attributes.position.array].every(Number.isFinite));
console.log('Surface finish: canopy clears hull, bounded batched fittings, original lights/fuel/flight boundaries and finite rock geometry pass');
